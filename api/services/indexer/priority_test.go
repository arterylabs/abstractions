package indexer

import (
	"testing"

	"github.com/stretchr/testify/assert"
)

func TestClassifyFile(t *testing.T) {
	assert.Equal(t, PriorityHigh, ClassifyFile("internal/auth/jwt.go"))
	assert.Equal(t, PriorityLow, ClassifyFile("README.md"))
	assert.Equal(t, PriorityLow, ClassifyFile("auth_test.go"))
	assert.Equal(t, PriorityMedium, ClassifyFile("config.yaml"))
}

func TestBuildEmbedText(t *testing.T) {
	text := BuildEmbedText("auth/jwt.go", "go", "ValidateToken", "function", "validates JWTs", []string{"auth", "jwt"})
	assert.Contains(t, text, "path: auth/jwt.go")
	assert.Contains(t, text, "ValidateToken")
	assert.Contains(t, text, "summary: validates JWTs")
}

func TestIsBinaryContent(t *testing.T) {
	assert.True(t, IsBinaryContent([]byte{0x00, 0x01, 0x02}))
	assert.False(t, IsBinaryContent([]byte("package main\n")))
}

func TestIsGeneratedContent(t *testing.T) {
	assert.True(t, IsGeneratedContent("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage pb\n"))
	assert.False(t, IsGeneratedContent("package main\nfunc main() {}\n"))
}
